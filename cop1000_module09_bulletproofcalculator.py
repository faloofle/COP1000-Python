# Asking for the inputs and checking if valid
try:
    num1_input = input("Enter the first number: ")
    num1 = float(num1_input)

    num2_input = input("Enter the second number: ")
    num2 = float(num2_input)

    operator = input("Enter the operation (+, -, *, /): ").strip()
    valid_operators = ['+', '-', '*', '/']

    if operator not in valid_operators:
        print(f"Error: Invalid operator '{operator}': Please use one of {valid_operators}.")
    elif operator == '/' and num2 == 0:
        print("Error: Division by zero is not allowed.")
    else:
        result = eval(str(num1) + operator + str(num2))
        print(f"The result of {num1} {operator} {num2} is {result}.")

except ValueError:
    print("Error: One of your inputs was not a valid number.")
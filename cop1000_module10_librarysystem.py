#making the class
class Book:
    def __init__(self, title, author, availability):
        self.title = title
        self.author = author
        self.availability = availability

    def display_info(self):
        print(f"Title: {self.title}")
        print(f"Author: {self.author}")
        print(f"Availability: {self.availability}\n")

    def check_out(self):
        if self.availability:
            self.availability = False
            print(f"{self.title} has been checked out.\n")
        else:
            print(f"{self.title} is already checked out.\n")

    def display_all(books):
        for book in books:
            book.display_info()
#each books
book1 = Book("The Great Gatsby", "F. Scott Fitzgerald", True)
book2 = Book("To Kill a Mockingbird", "Harper Lee", False)
book3 = Book("1984", "George Orwell", True)


book1.display_info()
book1.check_out()

book2.display_info()
book2.check_out()

book3.display_info()
book3.check_out()

# Display all books remaining status
print("----- Final Book Status -----")
Book.display_all([book1, book2, book3])
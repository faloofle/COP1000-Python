def load_data(filename):
    records = []
    try:
        with open(filename, mode="r", newline="", encoding="utf-8") as file:
            reader = csv.reader(file)
            header = next(reader)
            for row in reader:
                if row:
                    Investment=float(row[0])
                    Gains=float(row[1])
                    Losses=float(row[2])
                    records.append((Investment, Gains, Losses))
            print(f"Loaded {len(records)} records from {filename}\n")
    except FileNotFoundError:
        print(f"Error: {filename} couldnt be found")
    return records

def analyze_data(records):
  with open("data.csv", mode="r", newline="", encoding="utf-8") as file:
    reader = csv.reader(file)
    header = next(reader)
    for row in reader:
        investments.append(float(row[0]))
        gains.append(float(row[1]))
        losses.append(float(row[2]))

  net_profit = sum(gains) - sum(losses)
  avg_investment = sum(investments) / len(investments)
  highest_profit = max(gains)
  highest_loss = max(losses)
  total_investments = sum(investments)
  total_gains = sum(gains)
  total_losses = sum(losses)
  roi = (net_profit / sum(investments)) * 100

def display_results():
  print("Summary of Investments, gains and losses are calculated from the deviation from the original investment")
  print("-" * 40)
  print(f"Net Profits: ${net_profit:,.2f}")
  print(f"Total Investments: ${total_investments:,.2f}")
  print(f"Total Gains: ${total_gains:,.2f}")
  print(f"Total Losses: ${total_losses:,.2f}")
  print(f"Average Investment: ${avg_investment:,.2f}")
  print(f"Highest Profit: ${highest_profit:,.2f}")
  print(f"Highest Loss: ${highest_loss:,.2f}")
  print(f"ROI: {roi:.2f}%")

def display_records(records):
    print(f"{'Investment':<12} | {'Gains':<10} | {'Losses':<10}")
    print("-" * 40)
    for inv, gain, loss in records:
        print(f"${inv:<11,.2f} | ${gain:<9,.2f} | ${loss:<9,.2f}")

def visualization(records):
  indices = list(range(1, len(records) + 1))
  profits_losses = [record[1] - record[2] for record in records]

  colors = ['green' if x >= 0 else 'red' for x in profits_losses]
  plt.bar(indices, profits_losses, color=colors)
  plt.xticks(indices)
  plt.xlabel("Investment Index")
  plt.ylabel("Net Profit / Loss ($)")
  plt.title("Net Profits/Losses")
  plt.grid(True, linestyle='--', alpha=0.5)
  plt.savefig("visualization.png")
  plt.show()


import csv
# define the CSV filename
filename = 'activity_log.csv'

# collect details
activities = []
for i in range(1, 4):
    print(f"--- Activity {i} ---")
    name = input("Enter activity name: ")
    minutes = input("Enter minutes spent: ")
    activities.append([name, minutes])

# write to csv file
with open(filename, mode='w', newline='') as file:
    writer = csv.writer(file)
    writer.writerow(['Activity Name', 'Minutes Spent'])
    writer.writerows(activities)

print("\nData is saved!\n")

# displaying full csv
with open(filename, mode='r') as file:
    reader = csv.reader(file)
    for row in reader:
        print(f"{row[0]}: {row[1]}")

#input to-do list
todo_list = []
todo_list.append(input("Enter the first thing you need to do: "))
todo_list.append(input("Enter the second thing you need to do: "))
todo_list.append(input("Enter the last thing you need to do: "))

print("\n-----------------------\n")

print("Your to do list:")
for index, task in enumerate(todo_list, 1):
    print(f"{index}. {task}")

print("\n-----------------------\n")

print(f"The total amount of tasks you have are: {len(todo_list)}")